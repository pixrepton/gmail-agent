def build_run_artifact_paths(run_dir: Path) -> dict[str, Path]:
    """Return canonical artifact paths for a run directory."""
    return {name: run_dir / filename for name, filename in RUN_ARTIFACT_FILENAMES.items()}


def empty_preflight_summary(*, warnings: list[str] | None = None) -> dict[str, Any]:
    """Return an initialized preflight summary."""
    warnings_list = list(warnings or [])
    status = PREFLIGHT_STATUS_OK if not warnings_list else PREFLIGHT_STATUS_WARNING
    return {"status": status, "checks": {}, "warnings": warnings_list}


def empty_doctor_summary() -> dict[str, Any]:
    """Return an initialized doctor summary."""
    return {
        "status": DOCTOR_STATUS_OK,
        "env_source": "",
        "warnings": [],
        "checks": {
            "config": {"status": CHECK_STATUS_OK},
        },
    }


