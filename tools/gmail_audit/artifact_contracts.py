def build_run_manifest(
    *,
    run_id: str,
    command: str,
    selector: dict[str, Any],
    mailbox: str,
    model: str,
    schema_path: str | None,
    source_run: str | None,
    push_daszek: bool,
    runtime_controls: dict[str, Any],
) -> dict[str, Any]:
    """Build a stable manifest object for a new run."""
    return {
        "run_id": run_id,
        "mode": RUN_MODE_SHADOW,
        "status": RUN_STATUS_RUNNING,
        "command": command,
        "selector": sanitize_for_storage(selector),
        "mailbox": mailbox,
        "model": model,
        "schema_path": str(Path(schema_path).resolve()) if schema_path else "",
        "source_run": source_run,
        "daszek_push_requested": push_daszek,
        "runtime_controls": sanitize_for_storage(runtime_controls),
        "env_source": "",
        "local_env_files": [],
        "preflight": empty_preflight_summary(),
        "telemetry": {},
        "started_at": datetime.now().astimezone().isoformat(),
        "completed_at": "",
    }


